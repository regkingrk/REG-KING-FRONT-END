/**
 * REG KING launch check. Run before every launch: `npm run prelaunch` (it also runs before `npm run build`
 * when LAUNCH=1). Exits with an error listing everything that must be fixed first.
 *
 * Checks the house rules (no purple, no pill buttons, no em dashes, no emoji, no fake reviews,
 * metrics or sample data, no cursor or looping animations) and the launch list
 * (custom domain, favicon, no "Made with AI" tag, privacy policy and terms pages).
 */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const problems = [];
const fail = (msg) => problems.push(msg);

const walk = (dir, out = []) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|css|mjs|html)$/.test(f)) out.push(p);
  }
  return out;
};
const files = [...walk("app"), ...walk("components"), ...walk("lib")];
const read = (f) => readFileSync(f, "utf8");

// --- House rules -----------------------------------------------------------
for (const f of files) {
  const s = read(f);
  const lines = s.split("\n");
  lines.forEach((line, i) => {
    const at = `${f}:${i + 1}`;
    if (/—/.test(line)) fail(`Em dash: ${at}`);
    if (/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}]/u.test(line)) fail(`Emoji or symbol character: ${at}`);
    if (/purple|violet|indigo|magenta|#(8b5cf6|7c3aed|a855f7|6d28d9|9333ea|c084fc)/i.test(line)) fail(`Purple colour: ${at}`);
    if (/made with (ai|claude|v0|lovable|bolt)|generated by|built with ai/i.test(line)) fail(`"Made with AI" style tag: ${at}`);
  });
  if (f.endsWith(".css")) {
    // A broken value (e.g. a missing bracket) makes browsers drop the rest of the stylesheet.
    const bare = s.replace(/\/\*[\s\S]*?\*\//g, "");
    let depth = 0;
    for (const ch of bare) if (ch === "{") depth++; else if (ch === "}" && --depth < 0) break;
    if (depth !== 0) fail(`Unbalanced braces in ${f}`);
    lines.forEach((line, i) => {
      const decl = line.replace(/\/\*.*?\*\//g, "");
      if ((decl.match(/\(/g) || []).length !== (decl.match(/\)/g) || []).length && /:\s*[^{]*;\s*$/.test(decl)) fail(`Unbalanced brackets: ${f}:${i + 1}`);
    });
    lines.forEach((line, i) => {
      if (/border-radius:\s*(999|9999)px/.test(line) && !/__dot|__tick/.test(lines.slice(Math.max(0, i - 12), i).join(" ").split("}").pop()))
        fail(`Pill shape (999px radius): ${f}:${i + 1}`);
      if (/cursor:\s*(none|url\()/.test(line)) fail(`Custom cursor: ${f}:${i + 1}`);
      if (/animation:[^;]*infinite/.test(line) && !/stock ticker: pauses on hover, off for reduced motion/.test(line)) fail(`Looping animation: ${f}:${i + 1}`);
    });
  } else if (/mousemove|pointermove/.test(s) && !/if \(!dragging/.test(s)) fail(`Cursor-following code (moves with the pointer without a drag): ${f}`);
}

// --- No fake or sample content ---------------------------------------------
const search = read("lib/search.ts");
if (/sample:\s*true/.test(search) || /samplePlates\(/.test(search)) fail("Sample plates still in lib/search.ts (load real Shopify, customer and DVLA stock).");
if (/PROTOTYPE: categories are worked out from word lists/.test(read("lib/filters.ts"))) fail("Buy categories still come from word lists in lib/filters.ts: tag plates in Shopify instead.");
if (/LAUNCH: confirm the font licence/.test(read("app/globals.css"))) fail("Plate font BS AU 145d: confirm with Hills Numberplates that the licence covers website use, then remove the LAUNCH note in app/globals.css.");
if (/Prototype only/.test(search)) fail("Prototype step that labels samples as REG KING stock is still in lib/search.ts.");
if (/Prototype/.test(read("components/SearchResults.tsx"))) fail("Prototype note still on the search results page.");
if (/Prototype/.test(read("components/TabViews.tsx"))) fail("Sell listing flow is still a prototype: connect accounts and listings, then remove the Prototype note in components/TabViews.tsx.");
{
  const views = read("components/SectionViews.tsx") + read("components/TabViews.tsx");
  if (/until the AI valuation connects/.test(views)) fail("AI valuation tool isn't connected yet: connect it and remove the Prototype note in components/TabViews.tsx.");
  if (/add each team member/.test(views)) fail("Team page has no profiles yet: add names, roles and photos in components/SectionViews.tsx.");
  if (/customer photos go here/.test(views)) fail("Gallery has no photos yet: add customer photos in components/SectionViews.tsx.");
  if (/their full text loads from Trustpilot and Google/.test(views)) fail("Reviews aren't connected yet: load them from the Trustpilot and Google feeds and remove the Prototype note in components/SectionViews.tsx.");
  if (/these are sample listings/.test(views)) fail("Customer plates on Buy are samples: connect real seller listings in components/SectionViews.tsx.");
}
if (/: null as Price/.test(read("lib/accessories.ts"))) fail("Surround and logo plate prices aren't set: fill in ACCESSORY_PRICES in lib/accessories.ts.");
if (/Prototype/.test(read("components/MakeTools.tsx"))) fail("Make basket is still a prototype: connect it to the Shopify cart and remove the Prototype note in components/MakeTools.tsx.");
if (read("components/Checkout.tsx").includes("PREVIEW: nothing is charged or ordered")) fail("Checkout: connect payments (card form, Pay in 3, Payl8r, deposits), orders and emails, then remove the PREVIEW note and banner in components/Checkout.tsx.");
if (read("lib/admin.ts").includes("PREVIEW: every record below is an EXAMPLE")) fail("Admin portal: replace the example records in lib/admin.ts with the database, add staff sign-in with two-step and server-side role checks.");
const brand = read("lib/brand.ts");
if (/sampleReviews|sampleLots|Example customer/.test(brand)) fail("Sample reviews or auction lots in lib/brand.ts.");
for (const f of files) if (/className="rk-sample"|>Sample</.test(read(f))) fail(`"Sample" label shown in ${f}`);

// --- Launch list --------------------------------------------------------------
if (!existsSync("app/favicon.ico") || !existsSync("app/icon.png") || !existsSync("app/apple-icon.png"))
  fail("Favicon missing (run npm run favicons).");
if (!existsSync("app/privacy-policy/page.tsx")) fail("Privacy policy page missing.");
if (!existsSync("app/terms-of-service/page.tsx")) fail("Terms and conditions page missing.");
{
  const brand = readFileSync("lib/brand.ts", "utf8");
  if (/export const tiktok[^\n]*href: null/.test(brand)) fail("TikTok link missing in lib/brand.ts (the hero icon has no link).");
  if (/KIT_WAS = /.test(readFileSync("lib/builder.ts", "utf8")) && !process.env.KITS_CONFIRMED)
    fail("Fitting kits: confirm the £2.99 usual price and kit contents, then set KITS_CONFIRMED=1.");
  if (readFileSync("components/PlateBuilder.tsx", "utf8").includes("PROTOTYPE: only the file name is kept"))
    fail("Make: road legal ID and proof uploads only keep the file name. Send them to secure storage with the order.");
  const info = readFileSync("lib/infoContent.ts", "utf8");
  if (/address: null as string \| null/.test(info)) fail("About and Contact: add the HQ street address in lib/infoContent.ts (HQ.address).");
  if (/hours: null as/.test(info)) fail("About: add the HQ opening hours in lib/infoContent.ts (HQ.hours).");
  if (readFileSync("components/InfoPages.tsx", "utf8").includes("PROTOTYPE: nothing is sent")) fail("Contact form: connect it to the Shopify contact form so messages reach support.");
  if (/GOOGLE_REVIEWS_URL: string \| null = null/.test(brand)) fail("Google reviews link missing in lib/brand.ts (GOOGLE_REVIEWS_URL).");
  // Accessories shop: products not in Shopify yet
  const shop = read("lib/accessoryShop.ts");
  const unpriced = [...shop.matchAll(/name: "([^"]+)"[^\n]*price: null(?![^\n]*(builder|soon: true))/g)].map((m) => m[1]);
  if (unpriced.length) fail(`Accessories: add these to Shopify with a price and photo (lib/accessoryShop.ts): ${unpriced.join(", ")}.`);
  if (shop.includes("CONFIRM: the Shopify listing doesn't say how many pads")) fail("Accessories: confirm the sticky pad pack is 10 pads (lib/accessoryShop.ts).");
  // Customer portal
  const portal = read("lib/portal.ts");
  if (/terms: null, version/.test(portal)) fail("Selling packages: add REG KING's own terms for each package in lib/portal.ts (TERMS) and set a version.");
  if (read("components/ListPlate.tsx").includes("lookup service isn't connected")) fail("List a Plate: connect a UK postcode lookup service (server side) in components/ListPlate.tsx.");
  if (read("components/AccountPortal.tsx").includes("Preview: not connected to Shopify yet")) fail("My account: connect Shopify customer accounts (Customer Account API sign-in and orders) and save submissions and requests to Shopify (see lib/portal.ts), then remove the preview notices.");
}
if (!process.env.SHOPIFY_STORE_DOMAIN || !process.env.SHOPIFY_STOREFRONT_TOKEN)
  fail("Shopify not connected (SHOPIFY_STORE_DOMAIN, SHOPIFY_STOREFRONT_TOKEN): the privacy and terms pages need it.");
const site = process.env.SITE_URL || "";
if (!/^https:\/\/(www\.)?regking\.co\.uk\/?$/.test(site))
  fail(`Custom domain not confirmed: set SITE_URL=https://regking.co.uk once the domain points at the new site (now: "${site || "not set"}").`);

if (problems.length) {
  console.error(`\nNOT READY TO LAUNCH. ${problems.length} thing(s) to fix:\n`);
  problems.forEach((p) => console.error(`  - ${p}`));
  console.error("");
  process.exit(1);
}
console.log("Launch check passed.");
